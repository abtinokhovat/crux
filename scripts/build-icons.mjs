// Builds web/vendor/icons.js: the Simple Icons (CC0) paths for every catalog technology that
// names an icon. Run after changing internal/catalog/catalog.yaml: npm run build:icons
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import * as si from "simple-icons";

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const cat = YAML.parse(readFileSync(root("internal/catalog/catalog.yaml"), "utf8"));
const bySlug = new Map(Object.values(si).filter((x) => x?.slug).map((x) => [x.slug, x]));
const out = {};
const missing = [];
for (const [id, t] of Object.entries(cat.tech)) {
  if (!t.icon) continue;
  const icon = bySlug.get(t.icon);
  if (!icon) { missing.push(`${id} (${t.icon})`); continue; }
  out[t.icon] = icon.path;
}
writeFileSync(
  root("web/vendor/icons.js"),
  `// Simple Icons (https://simpleicons.org, CC0 1.0) — 24×24 paths for the crux catalog.\n// Generated by scripts/build-icons.mjs. Do not edit.\nexport const ICONS = ${JSON.stringify(out)};\n`,
);
console.log(`✓ web/vendor/icons.js · ${Object.keys(out).length} icons`);
if (missing.length) console.log(`  no icon (monogram used): ${missing.join(", ")}`);
